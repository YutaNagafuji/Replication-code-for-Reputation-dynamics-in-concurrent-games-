#!/usr/bin/env python
# coding: utf-8
"""
Plotting Script for Figure 3 & Figure 4: Maximum Expected Payoff vs Q
Reference: "Reputation dynamics in concurrent games" (Nagafuji, Akiyama, and Sawa, 2026)

This script reads the CSV output from concurrent_games_ESS_simulation.py
(under probabilistic fusion f_Q) and plots the maximum expected resident payoff
across Q in [0, 1].

Compatible with:
  - New CSV format ('payoff_resident')
  - Legacy CSV format ('Wpp')
"""

import sys
import argparse
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.ticker import MaxNLocator


def plot_max_payoff_by_Q(
    csv_path: str,
    output_png: str = "max_payoff_by_Q.png",
    q_min: float = 0.0,
    q_max: float = 1.0,
    q_step: float = 0.01,
    show: bool = False,
    figsize: tuple = (8, 6),
):
    """
    Plots the maximum resident expected payoff against Q.

    Parameters:
      csv_path   : Path to input CSV generated by concurrent_games_ESS_simulation.py
      output_png : Path to save the output figure
      q_min      : Minimum Q (default: 0.0)
      q_max      : Maximum Q (default: 1.0)
      q_step     : Grid step for Q (default: 0.01)
      show       : If True, displays the plot interactively (for Jupyter/GUI)
      figsize    : Figure dimensions (default: (8, 6))
    """
    # =========================
    # 1. Load Data
    # =========================
    df = pd.read_csv(csv_path, dtype=str)

    # Detect payoff column: new schema ('payoff_resident') vs legacy schema ('Wpp')
    if "payoff_resident" in df.columns:
        payoff_col = "payoff_resident"
    elif "Wpp" in df.columns:
        payoff_col = "Wpp"
    else:
        raise KeyError(
            f"Neither 'payoff_resident' nor 'Wpp' column was found in {csv_path}."
        )

    if "Q" not in df.columns:
        raise KeyError(f"'Q' column was not found in {csv_path}.")

    # Cast numeric columns
    df["Q"] = pd.to_numeric(df["Q"], errors="coerce")
    df[payoff_col] = pd.to_numeric(df[payoff_col], errors="coerce")

    # Drop invalid rows and round Q to avoid floating-point mismatch
    df = df.dropna(subset=["Q", payoff_col])
    df["Q"] = df["Q"].round(4)

    # =========================
    # 2. Maximum Payoff per Q
    # =========================
    df_max = (
        df.groupby("Q", as_index=False)[payoff_col]
        .max()
        .sort_values("Q")
    )

    # =========================
    # 3. Fill Missing Q with 0.0
    # =========================
    # If no cooperative/semi-cooperative ESS exists for a specific Q,
    # the maximum payoff defaults to mutual defection (ALLD payoff = 0.0)
    q_full = np.round(
        np.arange(q_min, q_max + q_step / 2.0, q_step),
        4
    )

    df_max = (
        df_max.set_index("Q")
        .reindex(q_full)
        .fillna({payoff_col: 0.0})
        .rename_axis("Q")
        .reset_index()
    )

    # =========================
    # 4. Plot Styling (Paper Spec)
    # =========================
    plt.figure(figsize=figsize)

    plt.plot(
        df_max["Q"],
        df_max[payoff_col],
        marker="o",
        markersize=3,
        linewidth=1.5,
        color="black",
        markerfacecolor="black",
        markeredgecolor="black"
    )

    # Axis labels matching Figure 3/4 styling
    plt.xlabel("Q", fontsize=28)
    plt.ylabel("MAX Payoff", fontsize=28)

    # Tick label size matching paper formatting
    plt.tick_params(labelsize=24)

    # X-axis ticks fixed to [0.0, 0.5, 1.0]
    plt.xticks([0.0, 0.5, 1.0])

    # Y-axis coarse locator (up to ~5 major ticks)
    plt.gca().yaxis.set_major_locator(MaxNLocator(nbins=5, prune=None))

    plt.grid(True, alpha=0.3, linestyle="--")
    plt.tight_layout()

    plt.savefig(output_png, dpi=300)
    print(f"✔ Saved figure to: {output_png}")

    if show:
        plt.show()
    plt.close()

    return df_max


def main():
    parser = argparse.ArgumentParser(
        description="Plot maximum expected payoff vs Q from concurrent games simulation CSV."
    )
    parser.add_argument("input_csv", nargs="?", default="input.csv", help="Input CSV path")
    parser.add_argument("-o", "--output", default="max_payoff_by_Q.png", help="Output PNG path")
    parser.add_argument("--q-min", type=float, default=0.0, help="Minimum Q value (default: 0.0)")
    parser.add_argument("--q-max", type=float, default=1.0, help="Maximum Q value (default: 1.0)")
    parser.add_argument("--q-step", type=float, default=0.01, help="Grid step for Q (default: 0.01)")
    parser.add_argument("--show", action="store_true", help="Display plot interactively")

    args = parser.parse_args()

    plot_max_payoff_by_Q(
        csv_path=args.input_csv,
        output_png=args.output,
        q_min=args.q_min,
        q_max=args.q_max,
        q_step=args.q_step,
        show=args.show,
    )


if __name__ == "__main__":
    main()
